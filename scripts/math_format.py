# 三、每日一练的固定动作（对应 Day1 诊断出的根因）
# ============================================================
DAILY_ACTIONS = [
    ("第一步 · 抄", "把题目条件<b>抄成符号</b>：a、b 各是什么？符号关系先写一行"),
    ("第二步 · 标", "标出每个符号的<b>正负与位置</b>（能画图就画图）"),
    ("第三步 · 算", "一行一步，<b>等号对齐</b>，每步只做一件事"),
    ("第四步 · 验", "<b>代特殊值 / 估范围</b>验一遍，再写最终结果"),
]


def rules_html(kind="plain"):
    """十条书写规范（HTML）。"""
    rows = "".join(
        '<tr><td class="n">%s</td><td class="r">%s</td><td class="b">%s</td></tr>'
        % (n, r, b) for n, r, b in RULES)
    return ('<table class="mfcard %s"><thead><tr><th style="width:16%%;">规范</th>'
            '<th style="width:42%%;">要求</th><th>对照</th></tr></thead>'
            '<tbody>%s</tbody></table>' % (kind, rows))


def rules_text():
    """十条规范（纯文本，docx 用）。"""
    return "\n".join("%s —— %s（%s）" % (n, r, b) for n, r, b in RULES)


def by_qtype(qtype):
    """按题型的必写清单；没注册返回 None。"""
    return BY_QTYPE.get(qtype)


def must_html(qtype, kind="plain"):
    """题型必写清单（HTML）。"""
    d = BY_QTYPE.get(qtype)
    if not d:
        return ""
    items = "".join("<li>%s</li>" % m for m in d["must"])
    return ('<div class="mfmust %s"><div class="mh">✍ 这道题必须写出这几行'
            '（漏一行就丢一分）</div><ol>%s</ol>'
            '<div class="mtr">⚠ %s</div></div>' % (kind, items, d["trap"]))


def must_text(qtype):
    d = BY_QTYPE.get(qtype)
    if not d:
        return ""
    out = ["【本题必写】"]
    for i, m in enumerate(d["must"], 1):
        out.append("  %d. %s" % (i, re.sub(r'<[^>]+>', '', m)))
    out.append("⚠ " + re.sub(r'<[^>]+>', '', d["trap"]))
    return "\n".join(out)


def actions_html():
    """每日四步固定动作（HTML）。"""
    rows = "".join('<li><b>%s</b>：%s</li>' % (n, t) for n, t in DAILY_ACTIONS)
    return '<ol class="mfact">%s</ol>' % rows


