"""题型注册表 —— 学生做题前必须先给题目命名（阶段20）。

为什么要题型名？
  讲义里已经教会「每个知识点背后的思维模型」，但**模型不会自己跳出来**——
  孩子做题时最大的问题是：看到题目，认不出这是哪一类，于是套错方法或直接放弃。
  所以每道题都要有名字。认题型 = 选方法。这是「归类」动作的外化。

四段结构（每种题型固定）：
  name     题型名（孩子要写出来的那 4~6 个字）
  feature  判定特征 —— 怎么认出它是这一类（这是最值钱的一段）
  method   解法动作 —— 认出之后第一步做什么
  trap     这类题最容易栽在哪

语病类型（病句题专用，挂在病句题下面）：
  成分残缺 / 句式杂糅 / 重复赘余 / 否定不当 / 搭配不当 / 两面对一面 / 语序不当
"""

# kind_cn：DSL 的 MC/FILL/JUDGE → 中文题型大类
KIND_CN = {"MC": "选择题", "FILL": "填空题", "JUDGE": "简答题"}

# ======================= 数学题型 =======================
MATH_TYPES = {
    "程序框图题": dict(
        feature="题干里出现「按下面的程序计算」「程序框图」「如图所示的程序」",
        method="把流程读成文字：做什么 → 判断 → 重复几遍，再逐步模拟",
        trap="漏数一次循环；或看错判断框在动作的上边还是下边（决定跑几趟）",
    ),
    "数轴辨析题": dict(
        feature="题干出现「数轴上 A、B 两点」，问大小、符号、相反数、绝对值",
        method="把数标到数轴上，用位置比大小、用距离定绝对值，别硬算",
        trap="负数比大小反着来；把倒数也当成数轴上的概念（倒数讲的是乘积=1）",
    ),
    "动点问题": dict(
        feature="有动点从某点出发，按速度运动，问某时刻在哪或相距多少",
        method="先写位置式：位置 = 起点 ± 速度 × t，再把问题翻译成「相等」或「相差多少」",
        trap="「相距 m」只列一个方程——追上前后是两种情况；解完不验 t ≥ 0",
    ),
    "行程问题": dict(
        feature="两车/两人从两地相向或同向出发，求相遇或追及时间",
        method="画线段图标出速度和路程，用「路程和 = 总路程」「路程差 = 初始距离」列式",
        trap="忘记判断是相向还是同向；单位没统一（千米/时 与 米/秒 混用）",
    ),
    "找规律题": dict(
        feature="给一列数，问第 n 个是几，或用代数式表示规律",
        method="先算相邻两项的差；差不一样再看相邻两项的倍数（分母不能为 0）",
        trap="数列长了就从头数到尾——只看相邻两项，永远不会乱",
    ),
    "规律应用题": dict(
        feature="棋子摆图案、日历、植树这类「第几个要几个」的实际问题",
        method="先确认是不是等差（每次多同一个数），再用 首项 + (n−1) × 公差",
        trap="把「第几个」和「共几个」搞混；公差算成相邻两项的差又乘了一次",
    ),
    "新定义题": dict(
        feature="题目自己给一个没学过的定义（如「配对数为 1/(1+a)」），再让你算",
        method="严格按题目给的定义代入，一个字都不要改；算完回代检验",
        trap="用自己学过的旧定义去套；代入时把运算顺序搞错",
    ),
    "有理数加减题": dict(
        feature="生活场景里的加减：行驶、增减、盈利亏损、计件、超零",
        method="先找「哪些量是相反意义的」，定成正负，再按「减法=加相反数」统一成加法",
        trap="符号丢、减号没变号；异号相加时符号没跟着绝对值大的那个数",
    ),
    "数轴平移题": dict(
        feature="图形（长方形/三角）在数轴上左右移动，问某个点的位置或移动距离",
        method="抓住「一个点」作为基准：它从哪到哪，移动多少，加到坐标上",
        trap="移动方向看反；把「图形移动」和「点的坐标变化」混为一谈",
    ),
    "面积重叠题": dict(
        feature="两个图形（时段/区间）在数轴上覆盖，问重叠部分或空隙部分的长度",
        method="先画线段图；重叠 = 甲 + 乙 − 从头到尾的总长；空隙 = 总长 − 覆盖部分",
        trap="端点算重了（第1节到第4节是 3 个单位不是 4 个）；不画图硬算",
    ),
    "数形结合题": dict(
        feature="题干给出图形的边长、宽高，要求某个点的坐标或某个式子的值",
        method="把几何量（长、宽、高）翻译成数轴上的坐标，再列式",
        trap="图上标的方向看反；单位换算时把「几格」当「几个单位」",
    ),
    "比例应用题": dict(
        feature="涉及「标准重量/标准产量」「每箱 X 千克为标准」这类按标准比较",
        method="先找准「哪个是标准」，算出实际与标准的差，再判断是多是少",
        trap="只算差不算百分比；比较的对象搞错（跟标准比还是跟上次比）",
    ),
    "绝对值最值题": dict(
        feature="题干里出现「｜ax＋b｜」这种带系数的绝对值，要求求某个代数式的最大值/最小值",
        method="先把条件换元成「｜u｜＋｜v｜＝定值」，在坐标系里画菱形（或在数轴上分段），"
               "最值一定在顶点取到——把四个顶点代进去比大小，不用整条边去试",
        trap="把两个绝对值当成各自独立（以为每个都能同时取到）；只在端点试而漏掉中间顶点；"
             "换元后忘了反代回原变量",
    ),
    "绝对值分段题": dict(
        feature="一个式子里有两三个绝对值（系数不同），要求它的最小值，或含参数讨论",
        method="先找零点把式子按符号分段，每段化简成一次函数；"
               "最小值只可能在「某段的最优点」或「分段点」上，逐段比",
        trap="分段点漏了；某段算出负数说明那一段的符号假设错了；"
             "含参数时只试了一个参数值就下结论",
    ),
}

# ======================= 语文题型 =======================
CHINESE_TYPES = {
    "病句辨析题": dict(
        feature="选项里有一句话是「没有语病」的，或者让你指出哪句有语病",
        method="按清单挨个扫：成分（谁+干什么+对谁）、搭配（主语跟谓语配不配）、两面、重复",
        trap="看到别扭就排除——别扭不可靠，要按清单查完再定",
    ),
    "病句修改题": dict(
        feature="给一句有语病的话，要求改一处并说明改法",
        method="先找信号词（「通过……使」「之所以……的原因」），判断病在成分还是杂糅，再动刀",
        trap="只改不说，或者说了病因却没点明「删了哪句、为什么删」",
    ),
    "古诗鉴赏题": dict(
        feature="给一句诗，问它写出了什么、妙在哪里",
        method="三块一起给：手法 + 内容效果 + 情感；先回原文找到那句话",
        trap="只写情感，漏掉手法和效果——那是最常见的丢分",
    ),
    "炼字赏析题": dict(
        feature="指定某个字词问好在哪，常见问法「加点词有什么妙处」",
        method="三步比较：这个词的意思 → 换成别的字差在哪 → 换完画面少了什么",
        trap="只解释字面意思，不比较；忘了落到情感上",
    ),
    "表现手法题": dict(
        feature="问用了什么手法，或要求说出「表达效果」",
        method="先认手法（比喻/拟人/排比/虚实结合/对比），再说这样写写出了什么好处",
        trap="手法只报名字不说明效果；脱离原文硬背手法清单",
    ),
    "句段作用题": dict(
        feature="问某段的作用，或问「这段能不能删」",
        method="先定位置（首/中/末），再四格扫描：内容 / 结构 / 情感 / 主旨",
        trap="角度不全——只答结构，漏掉内容和主旨",
    ),
    "标题含义题": dict(
        feature="问文章标题的含义或标题的作用",
        method="分两层写：表层（字面写了什么）+ 深层（暗示了什么情感或主旨）",
        trap="只写表层；或只答主旨作用，漏掉字面这一层",
    ),
    "主旨概括题": dict(
        feature="问文章主要写了什么、表达了什么情感",
        method="先概括内容，再往上走一层：作者借它说明了什么道理或态度",
        trap="停在内容层——概括情节不等于主旨",
    ),
    "对比阅读题": dict(
        feature="给两段（两首诗/两个人物）问异同或比较",
        method="两步：找不同（谁的表达更冷/更直白）→ 说意味（这说明作者怎样的情感）",
        trap="只做第一步；或两篇各写一段却不用「比」字，阅卷不认",
    ),
    "词语辨析题": dict(
        feature="给近义词选一个，或问加点词的意思",
        method="先看词义差别，再看它放在这句话里搭不搭得上",
        trap="凭语感选，不看具体语境",
    ),
    "古诗默写题": dict(
        feature="直接填原句，含错别字",
        method="逐字落实，写完回读一遍检查同音字",
        trap="同音字写错（shi／shi 这类），一字之差全错",
    ),
    "文言实词题": dict(
        feature="古诗文言里某个词的意思，与今天的意思不同",
        method="记住古今异义（如「走」古义=跑，「妻子」=妻和子）",
        trap="拿今天的意思去解释古文",
    ),
}

# ======================= 英语题型 =======================
ENGLISH_TYPES = {
    "语音辨析题": dict(
        feature="给出划线部分，问读音与其他不同的一项",
        method="念出声；按组合发音规则判断（ch/sh/ph/th/wh、oo/oa/ow/ou）",
        trap="只看字母组合不念；清浊音不分（如 th 的清浊）",
    ),
    "细节理解题": dict(
        feature="问文中某句事实、时间、地点、人物",
        method="先圈关键词，再回原文定位，比对选项与原文",
        trap="凭印象选；选项偷换主语或时间",
    ),
    "主旨大意题": dict(
        feature="问文章主要讲什么，或最佳标题",
        method="看首末段和转折词，跳过例子抓反复出现的核心话题",
        trap="选了一个具体例子当主旨；标题太具体或太宽泛",
    ),
    "语法填空题": dict(
        feature="选 be 动词、三单、介词等",
        method="先找主语中心词，看单复数；再看时态线索",
        trap="忽略第三人称单数；a/an 不会选",
    ),
    "词义辨析题": dict(
        feature="选正确的名词或动词填空",
        method="看句子要表达什么意思，再看哪个词能对上语境",
        trap="只看中文意思对应，不看句子里的搭配",
    ),
    "时态辨析题": dict(
        feature="给动词形式或选时态",
        method="找时间状语（yesterday / now / every day）→ 定时态 → 再看主语定单复数",
        trap="忽略时间状语，凭中文时态感选",
    ),
}

ALL_TYPES = {}
ALL_TYPES.update(MATH_TYPES)
ALL_TYPES.update(CHINESE_TYPES)
ALL_TYPES.update(ENGLISH_TYPES)

# ======================= 语病类型（病句题专用） =======================
# 每种语病给出「怎么认出来」——这是病句题真正要记的东西。
BINGJU_TYPES = {
    "成分残缺": dict(
        signal="句子里找不到主语了",
        signal_e="「通过……」或「在……过程中」开头，句子却没说我/谁怎么样",
        fix="① 删介词（「通过这次活动」作主语）② 删「使」（「我们」作主语）③ 补主语（「同学们」）",
    ),
    "句式杂糅": dict(
        signal="两套说法套在一句里",
        signal_e="「之所以……的原因，是因为」「的原因是……」这种叠罗汉说法",
        fix="删掉多余的说法：「他进步的原因，是因为复盘」→ 只留「他进步，是因为复盘」",
    ),
    "重复赘余": dict(
        signal="意思说了两遍",
        signal_e="「比上次增加了很多」「比原来完成得快了很多」——「比」已经含比较，「很多」又说一遍",
        fix="删掉重复的那部分：「比上次增加了不少」「比原来完成得快多了」",
    ),
    "否定不当": dict(
        signal="否定词用多了或用错了",
        signal_e="「防止……不再发生」——双重否定把意思说反了",
        fix="删掉多余的否定：「防止这类事故再次发生」",
    ),
    "搭配不当": dict(
        signal="主语跟谓语搭不上，或动词跟宾语搭不上",
        signal_e="如「提高……水平」中的主语是具体的人时",
        fix="换掉搭不上的一方，或改换主语",
    ),
    "两面对一面": dict(
        signal="前面两面，后面一面",
        signal_e="「能否取得进步，关键在于是否努力」——这个是两面对两面，**通的**；"
                "「能否进步，关键在于努力」才是错（两面 vs 一面）",
        fix="改成前后对应：「能否进步，关键在于是否努力」",
    ),
    "语序不当": dict(
        signal="谁先谁后放错了",
        signal_e="多层定语、多重状语的位置颠倒",
        fix="按「时间/地点/方式」的先后顺序调整",
    ),
}


def get(name):
    return ALL_TYPES.get(name)


def check_all_types_used():
    """返回注册了但从未被任何题使用的题型名（用于发现注册表虚胖）。"""
    import io, os, re
    used = set()
    for d in range(1, 9):
        p = "_p5/day%d.txt" % d
        if not os.path.exists(p):
            continue
        for ln in io.open(p, encoding="utf-8").read().split("\n"):
            m = re.match(r"^(?:MC|FILL|JUDGE)\|([^|]*)\|", ln)
            if m:
                m2 = re.search(r"【题型】([^<（(]*)", m.group(1))
                if m2:
                    used.add(m2.group(1).strip())
    return sorted(set(ALL_TYPES) - used)


