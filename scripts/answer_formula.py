ENGLISH_FORMULA = {}

ALL_FORMULA = {}
ALL_FORMULA.update(CHINESE_FORMULA)
ALL_FORMULA.update(ENGLISH_FORMULA)


def get(name):
    """按题型名取答题公式；没有就返回 None（客观题不挂公式）。"""
    return ALL_FORMULA.get(name)


def names():
    return sorted(ALL_FORMULA.keys())


def card_html(qtype, kind="plain"):
    """单题的答题公式卡（HTML）。

    kind: plain 纯净（作答纸用，公式印在题干上方）/ key 答案册（多一句 tips）
    """
    d = ALL_FORMULA.get(qtype)
    if not d:
        return ""
    rows = "".join(
        '<tr><td class="k">%s</td><td class="v">%s</td></tr>' % (k, v)
        for k, v in d["parts"])
    return (
        '<div class="afcard %s"><div class="afh">✍ 答题公式 · %s</div>'
        '<div class="aff">%s</div>'
        '<table class="aft"><tbody>%s</tbody></table>'
        '<div class="afs">范例：%s</div>'
        '%s</div>'
        % (kind, qtype, d["formula"], rows, d["sample"],
           ('<div class="aftip">%s</div>' % d["tip"]) if kind == "key" else ""))


def card_text(qtype):
    """纯文本版（docx 用）。"""
    d = ALL_FORMULA.get(qtype)
    if not d:
        return ""
    out = ["【答题公式 · %s】%s" % (qtype, d["formula"])]
    for k, v in d["parts"]:
        out.append("  %s：%s" % (k, v))
    return "\n".join(out)


if __name__ == "__main__":
    print("答题公式卡 · %d 条" % len(ALL_FORMULA))
    for k in names():
        d = ALL_FORMULA[k]
        print("\n  【%s】%s" % (k, d["formula"]))
        for a, b in d["parts"]:
            print("     %s — %s" % (a, b))
